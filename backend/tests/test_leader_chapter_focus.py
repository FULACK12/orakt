from app.dossier_evidence_selection import select
from app.company_history_dossier import chapter_packet


def test_capital_prefers_cash_and_debt_not_generic_product_prose():
    passages=[{'id':'intro','text':'We design operating systems and innovative products.'},
        {'id':'cash','text':'Cash generated by operating activities increased with earnings.'},
        {'id':'debt','text':'The company had no debt outstanding and no related interest expense.'},
        {'id':'uses','text':'Capital expenditures funded new retail stores.'},
        {'id':'risk','text':'Our investment portfolio contains marketable securities.'}]
    selected,_=select(passages,'capital')
    assert {p['id'] for p in selected}=={'cash','debt','uses','risk'}


def test_core_income_comparisons_precede_alphabetical_tax_items():
    def comparison(i,name):
        fact={'evidence_id':str(i),'value':100,'period_end':'2009-09-26'}
        return {'id':str(i),'concept':name,'unit':'USD','periodType':'annual','comparisonBasis':'same_duration_year_over_year',
            'direction':'increase','change':'1','changePercent':'1','evidence_refs':[str(i)],'current':fact,'previous':fact}
    comps=[comparison(i,'AccruedRevenue'+str(i)) for i in range(12)]+[comparison(20,'SalesRevenueNet'),comparison(21,'NetIncomeLoss')]
    p={'ticker':'AAPL','facts':[],'financial_ledger':{'accountingRules':[],'comparisons':comps}}
    selected=chapter_packet(p,'financial')['financial_ledger']['comparisons']
    assert [c['concept'] for c in selected[:2]]==['SalesRevenueNet','NetIncomeLoss']
